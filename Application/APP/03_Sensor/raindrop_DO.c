
#include "hrtos.h"
#include "hrtos_hal.h"

/*
 * =========================================================
 * 雨滴传感器DO + 4位数码管显示示例
 * ---------------------------------------------------------
 * 功能：
 * 1. 初始化雨滴传感器
 * 2. 读取雨滴传感器数字量DO
 * 3. 使用4位数码管显示检测状态
 *
 * DO状态：
 *     0：检测到雨滴
 *     1：未检测到雨滴
 *
 * 数码管显示：
 *     0000：检测到雨滴
 *     0001：未检测到雨滴
 * =========================================================
 */


/*------------------------------------------------
 * 雨滴传感器数字量状态
 *------------------------------------------------*/
unsigned char raindrop_do = 1;


/*------------------------------------------------
 * 雨滴传感器DO读取任务
 *------------------------------------------------*/
void task_raindrop_read(void)
{
    while(1)
    {
        /* 读取雨滴传感器数字量 */
        raindrop_do = drv_raindrop_read_do();

        /*
         * 周期读取传感器状态
         */
        os_delay(50);
    }
}


/*------------------------------------------------
 * 数码管显示任务
 *------------------------------------------------*/
void task_seg_display(void)
{
    while(1)
    {
        /*
         * 显示雨滴传感器状态
         *
         * 0000：检测到雨滴
         * 0001：未检测到雨滴
         */
        drv_seg_display(0, 0);
        drv_seg_display(1, 0);
        drv_seg_display(2, 0);
        drv_seg_display(3, raindrop_do);
    }
}


/**
 * @brief 雨滴传感器DO示例初始化
 */
void hrtos_main(void)
{
    /* 初始化雨滴传感器 */
    drv_raindrop_init();

    /* 初始化数码管 */
    drv_seg_init();

    /* 创建雨滴传感器读取任务 */
    os_task_create(
        task_raindrop_read,
        2,
        2,
        4
    );

    /* 创建数码管显示任务 */
    os_task_create(
        task_seg_display,
        3,
        2,
        4
    );
}

