
#include "hrtos.h"
#include "hrtos_hal.h"

/*
 * =========================================================
 * 红外避障 + 4位数码管显示示例
 * ---------------------------------------------------------
 * 功能：
 * 1. 初始化红外避障传感器
 * 2. 读取红外避障状态
 * 3. 使用4位数码管显示检测状态
 *
 * 显示：
 *     0000：检测到障碍物
 *     0001：未检测到障碍物
 * =========================================================
 */


/*------------------------------------------------
 * 红外避障状态
 *------------------------------------------------*/
unsigned char ir_state = 1;


/*------------------------------------------------
 * 红外避障读取任务
 *------------------------------------------------*/
void task_ir_read(void)
{
    while(1)
    {
        /* 读取红外避障状态 */
        ir_state = drv_ir_read();

        /*
         * 周期读取传感器状态
         */
        os_delay_ms(50);
    }
}


/*------------------------------------------------
 * 数码管显示任务
 *------------------------------------------------*/
void task_seg_display(void)
{
    while(1)
    {
        /*
         * 显示红外避障状态
         *
         * 0：检测到障碍物
         * 1：未检测到障碍物
         */
        drv_seg_display(0, 0);
        drv_seg_display(1, 0);
        drv_seg_display(2, 0);
        drv_seg_display(3, ir_state);
    }
}


/**
 * @brief 红外避障示例初始化
 */
void hrtos_main(void)
{
    /* 初始化红外避障传感器 */
    drv_ir_init();

    /* 初始化数码管 */
    drv_seg_init();

    /* 创建红外避障读取任务 */
    os_task_create(
        task_ir_read,
        2,
        2,
        4
    );

    /* 创建数码管显示任务 */
    os_task_create(
        task_seg_display,
        3,
        2,
        4
    );
}

