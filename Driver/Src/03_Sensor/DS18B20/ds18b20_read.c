#include "hrtos_hal.h"


/*------------------------------------------------
 * 读取温度
 *
 * 返回：
 * 温度值，单位为0.01℃
 *
 * 例如：
 * 25.25℃ -> 2525
 * -10.50℃ -> -1050
 *------------------------------------------------*/
signed int drv_ds18b20_read(void)
{
    /* 保存进入函数前的总中断状态 */
    unsigned char ea_state;

    /* DS18B20温度数据 */
    unsigned char low;
    unsigned char high;

    /* 合并后的16位原始温度数据 */
    unsigned int raw_data;

    /* 最终返回的温度值 */
    signed int value;

    /* 温度计算临时变量 */
    float temperature;


    /*------------------------------------------------
     * 关闭总中断
     *
     * DS18B20采用严格的单总线时序，
     * 防止中断打断数据通信。
     *------------------------------------------------*/
    ea_state = EA;
    EA = 0;


    /*------------------------------------------------
     * 发送复位信号
     *------------------------------------------------*/
    drv_ds18b20_reset();


    /*------------------------------------------------
     * 发送跳过ROM命令
     *
     * 0xCC：
     * Skip ROM，跳过ROM匹配。
     *
     * 当总线上只有一个DS18B20时，
     * 可以直接使用该命令。
     *------------------------------------------------*/
    drv_ds18b20_write_byte(0xCC);


    /*------------------------------------------------
     * 发送读取温度命令
     *
     * 0xBE：
     * Read Scratchpad，读取暂存器。
     *------------------------------------------------*/
    drv_ds18b20_write_byte(0xBE);


    /*------------------------------------------------
     * 读取温度数据
     *
     * DS18B20先发送低8位，
     * 再发送高8位。
     *------------------------------------------------*/
    low = drv_ds18b20_read_byte();
    high = drv_ds18b20_read_byte();


    /*------------------------------------------------
     * 恢复进入函数前的总中断状态
     *
     * 不直接使用EA = 1，
     * 避免调用函数前总中断本来就是关闭状态。
     *------------------------------------------------*/
    EA = ea_state;


    /*------------------------------------------------
     * 合并16位温度原始数据
     *
     * high：高8位
     * low ：低8位
     *
     * 最终：
     * raw_data = high << 8 | low
     *------------------------------------------------*/
    raw_data = high;
    raw_data <<= 8;
    raw_data |= low;


    /*------------------------------------------------
     * 将无符号原始数据转换为有符号温度数据
     *
     * DS18B20支持正负温度。
     *------------------------------------------------*/
    value = raw_data;


    /*------------------------------------------------
     * 转换为实际温度
     *
     * DS18B20默认12位分辨率，
     * 每个最低位代表0.0625℃。
     *------------------------------------------------*/
    temperature = value * 0.0625;


    /*------------------------------------------------
     * 转换为0.01℃单位
     *
     * 例如：
     * 25.36℃ -> 2536
     *
     * 加0.5或减0.5用于四舍五入。
     *------------------------------------------------*/
    value = temperature * 100 +
            (value > 0 ? 0.5 : -0.5);


    /*------------------------------------------------
     * 返回温度值
     *------------------------------------------------*/
    return value;
}