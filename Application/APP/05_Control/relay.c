
#include "hrtos.h"
#include "hrtos_hal.h"

/*
 * =========================================================
 * 继电器 + 4位数码管显示示例
 * ---------------------------------------------------------
 * 功能：
 * 1. 初始化继电器
 * 2. 控制继电器周期性吸合和释放
 * 3. 使用4位数码管显示当前继电器状态
 *
 * 继电器状态：
 *     0000：继电器关闭
 *     0001：继电器打开
 *
 * 工作过程：
 *     关闭  → 等待2秒
 *     打开  → 等待2秒
 *     循环执行
 * =========================================================
 */


/*------------------------------------------------
 * 继电器控制任务
 *------------------------------------------------*/
void task_relay_control(void)
{
    while(1)
    {
        /* 打开继电器 */
        drv_relay_on();

        /* 保持2秒 */
        os_delay(200);

        /* 关闭继电器 */
        drv_relay_off();

        /* 保持2秒 */
        os_delay(200);
    }
}


/*------------------------------------------------
 * 数码管显示任务
 *
 * 显示当前继电器状态
 *------------------------------------------------*/
void task_seg_display(void)
{
    unsigned char state;

    while(1)
    {
        /* 获取继电器当前状态 */
        state = drv_relay_get();

        /*
         * 显示继电器状态
         *
         * 0000：关闭
         * 0001：打开
         */
        drv_seg_display(0, 0);
        drv_seg_display(1, 0);
        drv_seg_display(2, 0);
        drv_seg_display(3, state);
    }
}


/**
 * @brief 继电器示例初始化
 */
void hrtos_main(void)
{
    /* 初始化继电器 */
    drv_relay_init();

    /* 初始化数码管 */
    drv_seg_init();

    /* 创建继电器控制任务 */
    os_task_create(
        task_relay_control,
        2,
        2,
        4
    );

    /* 创建数码管显示任务 */
    os_task_create(
        task_seg_display,
        3,
        2,
        4
    );
}

