
#include "hrtos.h"
#include "hrtos_hal.h"

/*
 * =========================================================
 * 人体红外 + 4位数码管显示示例
 * ---------------------------------------------------------
 * 功能：
 * 1. 初始化人体红外传感器
 * 2. 读取人体感应状态
 * 3. 使用4位数码管显示检测结果
 *
 * 人体红外状态：
 *     0001：检测到人体
 *     0000：未检测到人体
 * =========================================================
 */


/*------------------------------------------------
 * 人体感应状态
 *------------------------------------------------*/
unsigned char human_state = 0;


/*------------------------------------------------
 * 人体红外读取任务
 *------------------------------------------------*/
void task_human_read(void)
{
    while(1)
    {
        /* 读取人体感应状态 */
        human_state = drv_human_read();

        /*
         * 周期读取传感器
         */
        os_delay(50);
    }
}


/*------------------------------------------------
 * 数码管显示任务
 *------------------------------------------------*/
void task_seg_display(void)
{
    while(1)
    {
        /*
         * 显示人体感应状态
         *
         * 0001：检测到人体
         * 0000：未检测到人体
         */
        drv_seg_display(0, 0);
        drv_seg_display(1, 0);
        drv_seg_display(2, 0);
        drv_seg_display(3, human_state);
    }
}


/**
 * @brief 人体红外示例初始化
 */
void hrtos_main(void)
{
    /* 初始化人体红外传感器 */
    drv_human_init();

    /* 初始化数码管 */
    drv_seg_init();

    /* 创建人体红外读取任务 */
    os_task_create(
        task_human_read,
        2,
        2,
        4
    );

    /* 创建数码管显示任务 */
    os_task_create(
        task_seg_display,
        3,
        2,
        4
    );
}

