
#include "hrtos.h"
#include "hrtos_hal.h"

/*
 * =========================================================
 * XPT2046 + 4位数码管显示示例
 * ---------------------------------------------------------
 * 功能：
 * 1. 初始化XPT2046
 * 2. 读取XPT2046 ADC数据
 * 3. 使用4位数码管显示ADC转换结果
 *
 * ADC分辨率：
 *     12位
 *
 * ADC范围：
 *     0 ~ 4095
 *
 * 例如：
 *     0    -> 0000
 *     1024 -> 1024
 *     2048 -> 2048
 *     4095 -> 4095
 * =========================================================
 */


/*------------------------------------------------
 * XPT2046 ADC数据
 *------------------------------------------------*/
unsigned int xpt2046_adc_value = 0;


/*------------------------------------------------
 * XPT2046 ADC读取任务
 *------------------------------------------------*/
void task_xpt2046_read(void)
{
    while(1)
    {
        /*
         * 读取XPT2046 ADC
         *
         * 这里使用XPT2046的ADC通道控制命令。
         *
         * 0x90：
         * X+通道，单端模式
         *
         * 如果实际硬件使用其他通道，
         * 可以根据XPT2046配置修改此命令。
         */
        xpt2046_adc_value =
            drv_xpt2046_read_adc(0x90);

        /*
         * 周期读取ADC
         */
        os_delay_ms(50);
    }
}


/*------------------------------------------------
 * 数码管显示任务
 *------------------------------------------------*/
void task_seg_display(void)
{
    unsigned int value;

    while(1)
    {
        /* 获取ADC结果 */
        value = xpt2046_adc_value;

        /*
         * 显示12位ADC结果
         *
         * 范围：
         * 0000 ~ 4095
         */
        drv_seg_display(0, value / 1000);
        drv_seg_display(1, value / 100 % 10);
        drv_seg_display(2, value / 10 % 10);
        drv_seg_display(3, value % 10);
    }
}


/**
 * @brief XPT2046示例初始化
 */
void hrtos_main(void)
{
    /* 初始化XPT2046 */
    drv_xpt2046_init();

    /* 初始化数码管 */
    drv_seg_init();

    /* 创建XPT2046读取任务 */
    os_task_create(
        task_xpt2046_read,
        2,
        2,
        4
    );

    /* 创建数码管显示任务 */
    os_task_create(
        task_seg_display,
        2,
        2,
        4
    );
}

