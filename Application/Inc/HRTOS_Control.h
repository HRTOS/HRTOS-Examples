#ifndef __HRTOS_CONTROL_H__
#define __HRTOS_CONTROL_H__


/*================================================
 * PWM
 *================================================*/
#ifndef __DRV_PWM_H__
#define __DRV_PWM_H__

/*------------------------------------------------
 * PWM驱动库
 *
 * 功能：
 *      1. 初始化PCA PWM
 *      2. 设置PWM占空比
 *      3. 获取当前PWM占空比
 *      4. 停止PWM
 *
 * 适用：
 *      STC12C5A60S2等支持PCA/PWM的51单片机
 *
 * 说明：
 *      PWM使用PCA模块0输出。
 *      PWM0默认从P1.3引脚输出。
 *
 * PWM范围：
 *      0   ~ 100
 *      0   = 0%占空比
 *      100 = 100%占空比
 *------------------------------------------------*/

/* typedef unsigned char u8; */

extern u8 pwm_duty;


/*------------------------------------------------
 * PCA相关特殊功能寄存器
 *------------------------------------------------*/
sfr CCON    = 0xD8;     /* PCA控制寄存器 */
sfr CMOD    = 0xD9;     /* PCA工作模式寄存器 */
sfr CCAPM0  = 0xDA;     /* PCA模块0模式寄存器 */

sfr CL      = 0xE9;     /* PCA计数器低8位 */
sfr CCAP0L  = 0xEA;     /* PCA模块0捕获/比较寄存器低8位 */

sfr CH      = 0xF9;     /* PCA计数器高8位 */
sfr CCAP0H  = 0xFA;     /* PCA模块0捕获/比较寄存器高8位 */


/*------------------------------------------------
 * PCA启动/停止控制位
 *------------------------------------------------*/
sbit CR = CCON^6;       /* PCA运行控制位 */


/*------------------------------------------------
 * PCA引脚映射控制
 *------------------------------------------------*/
sfr AUXR1   = 0xA2;     /* 辅助寄存器1 */

/*
 * AUXR1.6：
 *      PCA_P4 = 0：PCA/PWM使用P1口
 *      PCA_P4 = 1：PCA/PWM切换至P4口
 *
 * PCA0/PWM0：
 *      P1.3（默认）
 *      P4.2（切换后）
 */
//sbit PCA_P4 = AUXR1^6;


/*------------------------------------------------
 * P1口模式控制寄存器
 *------------------------------------------------*/
sfr P1M1    = 0x91;     /* P1口模式寄存器1 */
sfr P1M0    = 0x92;     /* P1口模式寄存器0 */


/*------------------------------------------------
 * 初始化PWM
 *
 * 参数：
 *      无
 *
 * 返回：
 *      无
 *------------------------------------------------*/
void drv_pwm_init(void);


/*------------------------------------------------
 * 设置PWM占空比
 *
 * 参数：
 *      duty
 *          PWM占空比，范围0~100
 *
 * 返回：
 *      无
 *------------------------------------------------*/
void drv_pwm_set_duty(u8 duty);


/*------------------------------------------------
 * 获取PWM占空比
 *
 * 返回：
 *      当前PWM占空比，范围0~100
 *------------------------------------------------*/
u8 drv_pwm_get_duty(void);


/*------------------------------------------------
 * 停止PWM输出
 *
 * 返回：
 *      无
 *------------------------------------------------*/
void drv_pwm_stop(void);


/*------------------------------------------------
 * 启动PWM输出
 *
 * 返回：
 *      无
 *------------------------------------------------*/
void drv_pwm_start(void);

#endif /* __DRV_PWM_H__ */


/*================================================
 * 继电器
 *================================================*/
#ifndef __DRV_RELAY_H__
#define __DRV_RELAY_H__

/* typedef unsigned char u8; */


/*------------------------------------------------
 * 继电器驱动库
 *
 * 功能：
 *      1. 初始化继电器
 *      2. 吸合继电器
 *      3. 释放继电器
 *      4. 设置继电器状态
 *      5. 获取继电器状态
 *
 * 硬件：
 *      继电器模块：
 *          IN           -> P0.0
 *          GND/使能控制 -> P1.4
 *
 * 说明：
 *      本例程按照高电平触发继电器设计。
 *------------------------------------------------*/


/*------------------------------------------------
 * 继电器IO定义
 *------------------------------------------------*/
sbit RELAY_IN = P1^4;
sbit RELAY_EN = P0^0;


/*------------------------------------------------
 * 继电器当前状态
 *
 * 0：关闭
 * 1：打开
 *------------------------------------------------*/
extern u8 relay_state;


/*------------------------------------------------
 * 继电器吸合
 *------------------------------------------------*/
void drv_relay_on(void);


/*------------------------------------------------
 * 继电器释放
 *------------------------------------------------*/
void drv_relay_off(void);


/*------------------------------------------------
 * 设置继电器状态
 *
 * 参数：
 *      state
 *          0：关闭
 *          1：打开
 *------------------------------------------------*/
void drv_relay_set(u8 state);


/*------------------------------------------------
 * 获取继电器状态
 *
 * 返回：
 *      0：关闭
 *      1：打开
 *------------------------------------------------*/
u8 drv_relay_get(void);


/*------------------------------------------------
 * 继电器初始化
 *------------------------------------------------*/
void drv_relay_init(void);

#endif /* __DRV_RELAY_H__ */


#endif /* __HRTOS_CONTROL_H__ */